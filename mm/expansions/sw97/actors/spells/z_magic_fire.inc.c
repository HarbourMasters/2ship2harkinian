static void MagicFireMed_Init(Actor* thisx, PlayState* play) {
    MagicFire* this = THIS;

    this->action = 0;
    this->actionTimer = 0;
    Collider_InitCylinder(play, &this->collider);
    Collider_SetCylinder(play, &this->collider, &this->actor, &sCylinderInit);
    Collider_UpdateCylinder(&this->actor, &this->collider);
    this->actor.update = MagicFireMed_UpdateBeforeCast;
    this->actionTimer = 20;
    this->actor.room = -1;

    this->colliderScale.x = this->colliderScale.y = this->colliderScale.z = 0.0f;
    SkelCurve_Init(play, &this->skelCurve, &sMedLimbList, &sMedTransformUpdIdx);
    SkelCurve_SetAnim(&this->skelCurve, &sMedTransformUpdIdx, 0.0f, 10000.0f, 25.0f, 1.0f);
    this->alphaMultiplier = 1.0f;
}

static void MagicFireMed_Destroy(Actor* thisx, PlayState* play) {
    MagicFire* this = THIS;

    func_800876C8(play);

    SkelCurve_Destroy(play, &this->skelCurve);
}

static void MagicFireMed_UpdateBeforeCast(Actor* thisx, PlayState* play) {
    MagicFire* this = THIS;
    Player* player = GET_PLAYER(play);

    if ((play->msgCtx.msgMode == 0xD) || (play->msgCtx.msgMode == 0x11)) {
        Actor_Kill(&this->actor);
        return;
    }
    if (this->actionTimer > 0) {
        this->actionTimer--;
    } else {
        this->actor.update = MagicFireMed_Update;
        func_8002F7DC(&player->actor, NA_SE_PL_MAGIC_FIRE);
    }
    this->actor.world.pos = player->actor.world.pos;

    SkelCurve_Update(play, &this->skelCurve);
}

static void MagicFireMed_Update(Actor* thisx, PlayState* play) {
    MagicFire* this = THIS;
    Player* player = GET_PLAYER(play);
    s32 pad;

    this->actor.world.pos = player->actor.world.pos;
    if ((play->msgCtx.msgMode == 0xD) || (play->msgCtx.msgMode == 0x11)) {
        Actor_Kill(&this->actor);
        return;
    }
    // MM port: SoH `collider.info.toucher.damage` -> MM `collider.elem.atDmgInfo.damage`.
    if (this->action == DF_ACTION_EXPAND_SLOWLY) {
        this->collider.elem.atDmgInfo.damage = this->actionTimer + 25;
    } else if (this->action == DF_ACTION_STOP_EXPANDING) {
        this->collider.elem.atDmgInfo.damage = this->actionTimer;
    }
    Collider_UpdateCylinder(&this->actor, &this->collider);
    this->collider.dim.radius = (this->colliderScale.x * 325.0f);
    this->collider.dim.height = (this->colliderScale.y * 450.0f);
    this->collider.dim.yShift = (this->colliderScale.y * -225.0f);
    CollisionCheck_SetAT(play, &play->colChkCtx, &this->collider.base);

    switch (this->action) {
        case DF_ACTION_INITIALIZE:
            this->actionTimer = 30;
            this->colliderScale.x = this->colliderScale.y = this->colliderScale.z = 0.0f;
            this->actor.world.rot.x = this->actor.world.rot.y = this->actor.world.rot.z = 0;
            this->actor.shape.rot.x = this->actor.shape.rot.y = this->actor.shape.rot.z = 0;
            this->scalingSpeed = 0.08f;
            this->action++;
            break;
        case DF_ACTION_EXPAND_SLOWLY:
            if (this->actionTimer > 0) {
                Math_SmoothStepToF(&this->colliderScale.x, 0.4f, this->scalingSpeed, 0.1f, 0.001f);
                this->colliderScale.y = this->colliderScale.z = this->colliderScale.x;
            } else {
                this->actionTimer = 25;
                this->action++;
            }
            break;
        case DF_ACTION_STOP_EXPANDING:
            if (this->actionTimer <= 0) {
                this->actionTimer = 15;
                this->action++;
                this->scalingSpeed = 0.05f;
            }
            break;
        case DF_ACTION_EXPAND_QUICKLY:
            this->alphaMultiplier -= 8.0f / 119.000008f;
            this->colliderScale.x += this->scalingSpeed;
            this->colliderScale.y += this->scalingSpeed;
            this->colliderScale.z += this->scalingSpeed;
            thisx->scale.x += this->scalingSpeed * 0.05;
            thisx->scale.y += this->scalingSpeed * 0.05;
            thisx->scale.z += this->scalingSpeed * 0.05;
            if (this->alphaMultiplier <= 0.0f) {
                this->action = 0;
                Actor_Kill(&this->actor);
            }
            break;
    }
    if (this->actionTimer > 0) {
        this->actionTimer--;
    }

    SkelCurve_Update(play, &this->skelCurve);
}

// Static (no router mapping): scrolls the flame texture on limbs 1/2/3 via segments 8/9/10, exactly
// like the SoH original. MM port: SoH `SkelAnimeCurve*` -> MM `SkelCurve*`.
static s32 MagicFireMed_OverrideLimbDraw(PlayState* play, SkelCurve* skelCurve, s32 limbIndex, void* thisx) {
    MagicFire* this = THIS;

    OPEN_DISPS(play->state.gfxCtx);

    if (limbIndex == 1) {
        gSPSegment(POLY_XLU_DISP++, 8,
                   Gfx_TwoTexScroll(play->state.gfxCtx, 0, play->gameplayFrames % 0x80, 0, 0x20, 0x40, 1, 0,
                                    (u8)(play->gameplayFrames * -15), 0x20, 0x40));
    } else if (limbIndex == 2) {
        gSPSegment(POLY_XLU_DISP++, 9,
                   Gfx_TwoTexScroll(play->state.gfxCtx, 0, play->gameplayFrames % 0x80, 0, 0x20, 0x40, 1, 0,
                                    (u8)(play->gameplayFrames * -15), 0x20, 0x40));
    } else if (limbIndex == 3) {
        gSPSegment(POLY_XLU_DISP++, 0xA,
                   Gfx_TwoTexScroll(play->state.gfxCtx, 0, play->gameplayFrames % 0x80, 0, 0x20, 0x40, 1, 0,
                                    (u8)(play->gameplayFrames * -15), 0x20, 0x40));
    }

    CLOSE_DISPS(play->state.gfxCtx);

    return true;
}

static void MagicFireMed_Draw(Actor* thisx, PlayState* play) {
    GraphicsContext* gfxCtx = play->state.gfxCtx;
    MagicFire* this = THIS;

    if (this->action > 0) {
        OPEN_DISPS(gfxCtx);

        POLY_XLU_DISP = Gfx_CallSetupDL(POLY_XLU_DISP, 25);
        // Real OoT ovl_Magic_Fire colors: prim { 255, 200, 0 } (golden orange), env { 255, 0, 0 } (red).
        gDPSetPrimColor(POLY_XLU_DISP++, 0, 128, 255, 200, 0, (u8)(this->alphaMultiplier * 255));
        gDPSetEnvColor(POLY_XLU_DISP++, 255, 0, 0, (u8)(this->alphaMultiplier * 255));
        // MM port CRITICAL: last arg must be thisx (the callback's user pointer). MM's
        // SkelCurve_DrawLimb hands that pointer to the override callback; NULL crashes.
        SkelCurve_Draw(thisx, play, &this->skelCurve, MagicFireMed_OverrideLimbDraw, NULL, 1, thisx);

        CLOSE_DISPS(gfxCtx);
    }
}

